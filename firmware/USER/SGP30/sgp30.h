#ifndef __SGP30_H
#define __SGP30_H

#include "common.h"

/*==============================================================================
 *  SGP30 空气质量传感器（eCO2 / TVOC）
 *  接口：**I2C2（PF0/PF1）** —— 与 SHT30 的 I2C1 **分开走两条总线**。
 *        （SHT30=0x44 挂 I2C1；SGP30=0x58 挂 I2C2。要合并成一条就见下方 SGP30_I2C_HANDLE。）
 *        ★ 本板的 I2C2 由 CubeMX 生成（见 docs/CubeMX配置教程.md §12）。
 *
 *  ★ 关于"CO2 / 甲醛"：
 *      SGP30 实际输出的是 **eCO2（等效二氧化碳）** 与 **TVOC（总挥发性有机物）**。
 *      教材/课程里把它当作"CO2 / 甲醛"传感器使用 —— TVOC 即甲醛等有机气体的综合指标。
 *      本驱动按数据手册输出原始两个 16 位量，量纲：eCO2 = ppm，TVOC = ppb。
 *      SGP30 无温湿度补偿接口时读数仍可用，但精度依赖环境；如需更准，
 *      可用 SGP30_SetHumidity() 传入绝对湿度做补偿（本工程暂不启用）。
 *============================================================================*/

/* SGP30 默认地址 0x58（HAL 使用 8 位地址 0xB0） */
#define SGP30_I2C_ADDRESS       (0x58U << 1)

/* 命令（均为 2 字节，高字节在前） */
#define SGP30_CMD_IAQ_INIT      0x2003U     /* 初始化 IAQ（上电后调用一次） */
#define SGP30_CMD_MEASURE_IAQ   0x2008U     /* 测量 eCO2 + TVOC */
#define SGP30_CMD_SET_HUMIDITY  0x2061U     /* 设置绝对湿度补偿（可选） */

/* 预热时间：上电后 eCO2 恒为 400 属正常，约 15s 后才可信 */
#define SGP30_WARMUP_MS         15000U

/* 发测量命令后，手册要求等约 12ms 才能取结果 */
#define SGP30_MEASURE_WAIT_MS   12U

/* I2C 单次传输超时（原 100ms 太长：传感器不在时纯空转）*/
#define SGP30_I2C_TIMEOUT_MS    20U

/*==============================================================================
 *  ★ SGP30 挂在哪条 I2C 上
 *
 *  默认 **I2C1（PB6/PB7）** —— 与 SHT30 同一条总线。
 *
 *  ★ 本工程已切到 **I2C2**（与 SHT30 的 I2C1 分开；见文件末尾的 SGP30_I2C_HANDLE）。
 *     本板 CubeMX 把 I2C2 分配在 **PF0 = I2C2_SDA、PF1 = I2C2_SCL**
 *     （这两个脚在板上是**空闲的、且在 P7 排针上引出**）。
 *     如果想改用 PB10/PB11，在 CubeMX 里把 I2C2 的引脚改过去再生成即可。
 *
 *  要回到"与 SHT30 共用 I2C1"：把文件末尾那行改成 hi2c1 即可，不用动 CubeMX。
 *============================================================================*/
#define SGP30_I2C_HANDLE        hi2c2

/*==============================================================================
 *  初始化：下发 IAQ init 命令，退出时传感器进入可测量状态。
 *  注意：I2C 外设与引脚由 CubeMX 的 MX_I2Cx_Init() 配置（本工程 I2C2 = PF0/PF1），
 *        本函数只与传感器对话。
 *============================================================================*/
HAL_StatusTypeDef SGP30_Init(void);

/*==============================================================================
 *  ★ 两段式测量（非阻塞，给 RTOS 任务用）：
 *      SGP30_StartMeasure();                 // 发命令，立刻返回
 *      vTaskDelay(pdMS_TO_TICKS(SGP30_MEASURE_WAIT_MS));   // 让出 CPU
 *      SGP30_FetchIAQ(&eco2, &tvoc);         // 取结果 + CRC 校验
 *    这样 12ms 的等待是"睡着等"，不占 CPU、不饿别的任务。
 *============================================================================*/
HAL_StatusTypeDef SGP30_StartMeasure(void);
HAL_StatusTypeDef SGP30_FetchIAQ(u16 *eco2, u16 *tvoc);

/*==============================================================================
 *  一步到位版（内部 delay_ms 忙等）—— 只给"调度器没起来"的启动期用，
 *  任务里**不要**用（会占着 CPU 自旋）。
 *============================================================================*/
HAL_StatusTypeDef SGP30_ReadIAQ(u16 *eco2, u16 *tvoc);

/*==============================================================================
 *  湿度补偿（可选）：rh_abs 为绝对湿度，单位 mg/m³。
 *  绝对湿度 = 相对湿度% × 6.112 × e^(17.62T/(243.12+T)) / (273.15+T) × 216.7
 *  本工程未启用（无补偿时 SGP30 仍给出可用读数）。
 *============================================================================*/
HAL_StatusTypeDef SGP30_SetHumidity(u16 rh_abs);

#endif
