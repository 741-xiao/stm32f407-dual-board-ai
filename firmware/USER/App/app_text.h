/*==============================================================================
 *  app_text.h  ---  串口/网络输出用的中文字符串（GB18030 编码）
 *
 *  为什么不做成普通 C 字符串字面量：
 *    工程源文件是 UTF-8，ARMCC 遇到字符串里的多字节 UTF-8 会报
 *    "#870-D: invalid multibyte character sequence"。改成 GB18030 字节数组：
 *      1) 源文件里只剩 0xNN 的 ASCII 字符，编译安静通过；
 *      2) Windows 串口助手默认按 GBK/ANSI 解码，正好显示成中文；
 *      3) 上位机 Python 用 data.decode("gbk") 也能还原中文。
 *
 *  大部分条目由脚本生成；TXT_NAME_PRE / TXT_ID_PRE / TXT_EOL 是手写的，
 *  配合 app_id.h 一起用。
 *============================================================================*/
