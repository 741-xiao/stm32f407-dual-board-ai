#ifndef __LIGHT_H
#define __LIGHT_H

#include "common.h"

/*==============================================================================
 *  light.h  ---  光敏传感器（模拟量 AO）驱动
 *
 *  目标：把光敏模块的 AO 模拟输出，读成 0..4095 的具体数值（12 位 ADC）。
 *
 *  ---- ADC 归 CubeMX 管（2026-09 改造）----
 *  PC0(ADC1_IN10) 已在 .ioc 里配好：PCLK2/4、12 位、右对齐、单次、软件触发、
 *  采样时间 480 Cycles、NVIC 不使能。CubeMX 生成 Core/Src/adc.c 的
 *  MX_ADC1_Init()（main.c 调用），读取全部走 HAL。
 *  ★ 唯一例外：**校准**。本工程的 HAL 是裁剪版，`stm32f4xx_hal_adc_ex.c` 里
 *    没有 `HAL_ADCEx_Calibration_Start`，CMSIS 也没定义 `ADC_CR2.CAL` ——
 *    这 3 行只能在 `light.c` 里自己写寄存器（见那里注释）。
 *  ★ 要改 ADC 参数（含采样时间）请改 .ioc 重新生成，别改代码。
 *
 *  ---- 引脚 ----
 *      AO  ->  PC0      （ADC1_IN10；PC0..PC5 都空闲且带 ADC，这里用 PC0）
 *      VCC ->  3.3V
 *      GND ->  GND      （必须和单片机共地）
 *  ---- 关于 DO 那根线 ----
 *      模块的 DO 是内部比较器的 0/1 输出，本实验不用它，悬空即可。
 *
 *  ---- 数值含义 ----
 *      raw  : 0..4095    （ADC 原始值，与 AO 电压成正比）
 *      粗略电压 = raw / 4095 * 3.3V
 *      pct  : 0..100     （按满量程折算的百分比，方便显示）
 *   注意：光敏电阻是"光越强、阻值越小"，AO 电压随光照单调变化，但具体
 *   是"越亮越大"还是"越亮越小"取决于模块分压接法——上板看 [LIGHT] 打印实测，
 *   若方向反了，在显示处取反即可（本驱动只负责给"具体数值"）。
 *============================================================================*/

#define LIGHT_AO_MAX         4095U    /* 12 位满量程 */
#define LIGHT_AVG_N          8U       /* 平均值滤波的采样点数 */

/* 分压方向：本模块实测"越亮 -> AO 电压越低"，与直觉相反。
   打开取反后：越亮 -> 读数越大（0..4095），串口/上传帧/百分比方向一致。
   若换到方向相反的模块，把它改成 0 即可。 */
#define LIGHT_INVERT         1U

/* 配好 GPIOC/ADC1（PC0 模拟输入 + 校准）。幂等，可重复调用。 */
void Light_Init(void);

/* 单次转换，返回 0..4095。排错用。 */
u16  Light_ReadRaw(void);

/* LIGHT_AVG_N 次求平均，返回 0..4095。常规读数用这个，抖动小。 */
u16  Light_ReadAvg(void);

/* 平均值折算成百分比 0..100。 */
u8   Light_ReadPercent(void);

#endif
